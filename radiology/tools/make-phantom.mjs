// Writes deterministic synthetic CT and MR phantoms, never a patient, as viewer test fixtures.
// Geometry is in mm with the volume centre at the origin, x toward the patient's left, y posterior, z superior.
// A ruler on the viewer should find: cube side 30 mm, sphere diameter 24 mm, rod diameter 32 mm,
// and 145 mm along y from the sphere centre to the rod centre.
// The fat rim is the body ellipse minus the same ellipse shrunk by 12 mm on each semi axis.
