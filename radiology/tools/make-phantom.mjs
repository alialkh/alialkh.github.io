function check(ok, message) {
  if (!ok) throw new Error(message);
}

function labelAt(x, y, z) {
  for (let n = OBJECTS.length - 1; n >= 0; n--) {
    const { c, r, box, id } = OBJECTS[n];
    const u = (x - c[0]) / r[0], v = (y - c[1]) / r[1], w = (z - c[2]) / r[2];
    if (box ? Math.abs(u) <= 1 && Math.abs(v) <= 1 && Math.abs(w) <= 1 : u * u + v * v + w * w <= 1) return id;
  }
  return 0;
}

// mulberry32 seeded from an FNV-1a hash of the name, then Box-Muller.
function gaussian(name) {
  let s = [...name].reduce((h, ch) => Math.imul(h ^ ch.charCodeAt(0), 16777619), 2166136261) >>> 0;
  const uniform = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return () => Math.sqrt(-2 * Math.log(1 - uniform())) * Math.cos(2 * Math.PI * uniform());
}

function checkFov({ id, dims, spacing }) {
  const need = [0, 1, 2].map(a => 2 * Math.max(...OBJECTS.filter(o => Number.isFinite(o.r[a])).map(o => Math.abs(o.c[a]) + o.r[a])));
  const fov = dims.map((n, a) => n * spacing[a]);
  check(fov.every((f, a) => f >= need[a]), `${id}: the field of view ${fov.join(' x ')} mm is smaller than the phantom, which needs ${need.join(' x ')} mm. Raise --dims or --spacing.`);
}

function render({ id, dims: [nx, ny, nz], spacing: [sx, sy, sz], series }) {
  const labels = new Uint8Array(nx * ny * nz);
  const out = series.map(s => ({
    ...s, data: new Int16Array(labels.length), noise: gaussian(`${id}/${s.id}`),
    table: OBJECTS.reduce((t, o) => { t[o.id] = o[s.values]; return t; }, [AIR[s.values]]),
  }));
  const sums = Array.from({ length: 256 }, () => [0, 0, 0, 0]);
  const sub = new Uint8Array(8);
  for (let k = 0, p = 0; k < nz; k++) for (let j = 0; j < ny; j++) for (let i = 0; i < nx; i++, p++) {
    const x = (i + 0.5 - nx / 2) * sx, y = (j + 0.5 - ny / 2) * sy, z = (k + 0.5 - nz / 2) * sz;
    const label = labelAt(x, y, z);
    labels[p] = label;
    const sum = sums[label];
    sum[0] += i; sum[1] += j; sum[2] += k; sum[3]++;
    // 2x2x2 sub-samples soften the edges.
    for (let q = 0; q < 8; q++) sub[q] = labelAt(x + ((q & 1) - 0.5) * sx / 2, y + ((q >> 1 & 1) - 0.5) * sy / 2, z + ((q >> 2) - 0.5) * sz / 2);
    for (const s of out) {
      let v = 0;
      for (let q = 0; q < 8; q++) v += s.table[sub[q]];
      v /= 8;
      if (s.bias) v *= 1 - s.bias * y / (ny * sy); // brighter toward the front, s.bias from edge to edge
      if (label) v += s.sigma * s.noise();
      s.data[p] = Math.min(32767, Math.max(s.min, Math.round(v)));
    }
  }
  const centroids = {};
  sums.forEach(([i, j, k, n], label) => {
    if (label && n) centroids[label] = [i, j, k].map(v => Math.round(v / n * 10) / 10);
  });
  return { labels, centroids, series: out };
}

function finding({ dims: [nx, ny, nz], spacing }, { on, plane, id, title, text, series, window }) {
  const [i, j, k] = OBJ[on].c.map((mm, a) => Math.round(mm / spacing[a] + [nx, ny, nz][a] / 2 - 0.5));
  const frac = (v, n) => Math.round((v + 0.5) / n * 1000) / 1000;
  const up = frac(nz - 1 - k, nz);
  const { index, at } = {
    axial: { index: k, at: [frac(i, nx), frac(j, ny)] },
    coronal: { index: j, at: [frac(i, nx), up] },
    sagittal: { index: i, at: [frac(j, ny), up] },
  }[plane];
  return { id, title, text, plane, index, at, ...(series && { series }), ...(window && { window }) };
}

async function makeCase(out, spec) {
  checkFov(spec);
  const { labels, centroids, series } = render(spec);
  const grid = { dims: spec.dims, spacing: spec.spacing };
  for (const s of series) await writeVolume(join(out, spec.id, s.id), new Uint8Array(s.data.buffer), { ...grid, dtype: 'int16' });
  await writeVolume(join(out, spec.id, 'labels'), labels, { ...grid, dtype: 'uint8' });
  const { id, modality, region, title, summary } = spec;
  return {
    id, modality, region, title, summary, vignette: VIGNETTE,
    series: series.map(s => ({ id: s.id, name: s.name, url: `${id}/${s.id}/`, windows: s.windows, defaultWindow: s.defaultWindow })),
    labels: { url: `${id}/labels/`, names: NAMES, centroids },
    findings: spec.findings.map(f => finding(spec, f)),
    source: SOURCE,
  };
}

async function main() {
  const options = Object.fromEntries(['out', 'only', 'dims', 'spacing'].map(k => [k, { type: 'string' }]));
  const { values: o } = parseArgs({ options });
  const out = resolve(o.out ?? fileURLToPath(new URL('../viewer/test-fixtures/cases/', import.meta.url)));
  const picked = CASES.filter(c => !o.only || c.id === o.only);
  check(picked.length, `--only must be one of ${CASES.map(c => c.id).join(', ')}.\n${USAGE}`);
  check(o.only || !(o.dims || o.spacing), `--dims and --spacing need --only.\n${USAGE}`);
  const triple = (text, ok, what) => {
    const v = text.split(',').map(Number);
    check(v.length === 3 && v.every(ok), `${what} must be three ${what === '--dims' ? 'whole numbers' : 'numbers'} above zero, got ${text}`);
    return v;
  };
  const cases = [];
  for (const c of picked) {
    const dims = o.dims ? triple(o.dims, n => Number.isInteger(n) && n > 0, '--dims') : c.dims;
    const spacing = o.spacing ? triple(o.spacing, s => Number.isFinite(s) && s > 0, '--spacing') : c.spacing;
    cases.push(await makeCase(out, { ...c, dims, spacing }));
  }
  const manifest = join(out, 'manifest.json');
  // --only replaces its own entry and keeps the other cases already listed there.
  const kept = o.only && existsSync(manifest) ? JSON.parse(readFileSync(manifest, 'utf8')) : [];
  const listed = kept.some(c => c.id === o.only) ? kept.map(c => (c.id === o.only ? cases[0] : c)) : [...kept, ...cases];
  writeFileSync(manifest, `${JSON.stringify(listed, null, 2)}\n`);
  writeFileSync(join(out, 'empty.json'), '[]\n');
  const files = readdirSync(out, { recursive: true, withFileTypes: true }).filter(d => d.isFile());
  const total = files.reduce((n, d) => n + statSync(join(d.parentPath, d.name)).size, 0);
  console.log(`Wrote ${cases.length} cases to ${out}, ${total} bytes in total.`);
}

try {
  await main();
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
